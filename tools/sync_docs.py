"""Generate the cross-language contract; --check fails on documentation drift."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'physics_server'))
import server  # noqa: E402 - standalone script adds the sibling source directory
import world  # noqa: E402


def contract():
    masses = [1e-8, 0.003, 1.0, 1000.0, 40000.0]
    return {
        'protocol': server.PROTOCOL_VERSION,
        'port': server.DEFAULT_PORT,
        'header': server.HEADER_FLOATS,
        'body': server.BODY_FLOATS,
        'event': server.EVENT_FLOATS,
        'max_bodies': world.MAX_BODIES,
        'types': world.TYPE_KEYS,
        'events': {k: v for k, v in vars(world).items() if k.startswith('EV_')},
        'default_mass': list(world.DEFAULT_MASS.values()),
        'presets': list(world.PRESETS),
        'radius_samples': [[t, m, world.radius_for(t, m)] for t in world.TYPE_KEYS.values() for m in masses],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = contract()
    generated = {
        ROOT / 'docs/contract.json': json.dumps(data, indent=2) + '\n',
        ROOT / 'docs/protocol-reference.md': (
            '# Generated protocol reference\n\n'
            'Generated by `tools/sync_docs.py`; run it after changing the wire contract.\n\n'
            f'Protocol {data["protocol"]}; UDP port {data["port"]}; little-endian float32.\n\n'
            f'State: {data["header"]} header floats, {data["body"]} per body, {data["event"]} per event.\n'
            f'Maximum supported body count: {data["max_bodies"]}.\n\n'
            '| Body key | ID | Default mass |\n|---|---:|---:|\n'
            + ''.join(f'| {key} | {value} | {data["default_mass"][value]:g} |\n' for key, value in data['types'].items())
            + '\n| Event | Code |\n|---|---:|\n'
            + ''.join(f'| {key} | {value} |\n' for key, value in data['events'].items())
            + '\nScenarios: ' + ', '.join(f'`{p}`' for p in data['presets']) + '.\n'
        ),
    }
    stale = []
    for path, expected in generated.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding='utf-8')
    if stale:
        raise SystemExit('Generated documentation is stale: ' + ', '.join(stale) + '. Run tools/sync_docs.py.')
    print('Documentation contract check PASSED.' if args.check else 'Generated documentation updated.')


if __name__ == '__main__':
    main()
